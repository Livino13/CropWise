export function cropLabel(crop: string | null | undefined): string {
  if (!crop) return '—'
  if (CROP_LABELS[crop]) return CROP_LABELS[crop]
  return crop
    .replace(/_/g, ' ')
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
}
